"""
Builds a QGIS raster calculator expression that masks a cell-index raster to a
given list of VELMA outlet IDs, writing the expression to a text file. The
resulting raster can be converted to a point shapefile of outlets with an
editable attribute table for visualization in QGIS.
"""

outlet_list = '9510613 5431811 6586623 4900006 9018561 6586621 7581974 8962792 5086534 4909904 6547138 8664255 8451020 6207927 5168807 8126298 7785297 6438883 5992765 7050729 5175881 4979013 5044274 8841363 5756629 6998166 5725877 5450396 4916474 5136430 6985112 5415369 5348682 9477726 6401367 5076845 7709863 5532394 6648876 5739030 5149733 7240969 5415400 8929956 6287981 6412609 4956011 5540064 5139857 6493164 5050612 5358563 6465154 6028840 7185235 7713115 6709568 8132876 4942905 8802014 7962347 9510612 6827631 8460884 5618871 6496423 6368583 5001351 8277174 7122879 6465153 5037501 4919881 4959272 8378855 5165207 6596458 6491389 5168460 8608484 6087875 4890337 5073736 4978511 5576199 6729275 5014605 6909619 5873507 6248625 5697581 5319262 6255173 8539564 5487574 5286366 5743497 5858282 5083525 6019003 6248616 5956692 6176441 6435568 5060539 5719352 6665235 9346491 5070376 6671811 7375400 5572928 7716435 5952207 8634694 5933725 8342766 5397888 5391330 5273246'
raster_name = '"Snohomish_dem30m_dredgemask_EEX_indices@1"'
out_file = 'path/to/text.txt'

# 1. Split into individual IDs
values = outlet_list.split()

# 2. Build a list of equality expressions
exprs = [f'({raster_name} = {val})' for val in values]

# 3. Join them with " + " and wrap in (> 0)
inner_sum = ' + '.join(exprs)
mask = f'(({inner_sum}) > 0)'

# 4. Multiply by the original raster
final_expression = f'{mask} * {raster_name}'

# 5. Print it out
with open(out_file, "w") as f:
    f.write(final_expression)
print(f'Wrote to {out_file}')
